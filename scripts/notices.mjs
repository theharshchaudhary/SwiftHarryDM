// Regenerate THIRD_PARTY_NOTICES.md from the dependencies the shipped app actually uses:
// Rust crates reachable from the app (normal dependencies, Windows target) and the UI's
// runtime npm packages.   Usage: node scripts/notices.mjs
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--filter-platform", "x86_64-pc-windows-msvc"], {
    cwd: ROOT,
    maxBuffer: 256 << 20,
  }).toString(),
);
const pkgs = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const app = meta.packages.find((p) => p.name === "keepfetch");
const seen = new Set();
const stack = [app.id];
while (stack.length) {
  const id = stack.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const d of nodes.get(id)?.deps ?? []) {
    if (d.dep_kinds.some((k) => k.kind === null)) stack.push(d.pkg);
  }
}
const own = new Set(["keepfetch", "swiftdm-core"]);
const rust = [...seen]
  .map((id) => pkgs.get(id))
  .filter((p) => !own.has(p.name))
  .map((p) => [p.name, p.version, p.license ?? "see crate"])
  .sort((a, b) => a[0].localeCompare(b[0]));

const lock = JSON.parse(readFileSync(join(ROOT, "ui", "package-lock.json"), "utf8"));
const npm = Object.entries(lock.packages)
  .filter(([k, v]) => k.startsWith("node_modules/") && !v.dev)
  .map(([k, v]) => [k.slice("node_modules/".length), v.version, v.license ?? "see package"])
  .sort((a, b) => a[0].localeCompare(b[0]));

const table = (rows) => ["| Component | Version | License |", "|---|---|---|", ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");

writeFileSync(
  join(ROOT, "THIRD_PARTY_NOTICES.md"),
  `# Third-party components

Keepfetch is distributed under the MIT License (\`LICENSE.txt\`). This file lists the
components included in the app, generated by \`scripts/notices.mjs\`.

## Included as separate programs

| Component | Version | License | Use |
|---|---|---|---|
| FFmpeg / ffprobe | 8.1.3, small build | LGPL v2.1 or later | Joining video and audio, converting audio, checking files |
| LAME | 3.100 | LGPL v2 or later | MP3 encoding inside the FFmpeg build |

Keepfetch's FFmpeg is built from the official release sources
(https://ffmpeg.org/releases/ffmpeg-8.1.3.tar.xz and LAME 3.100 from
https://sourceforge.net/projects/lame/, both pinned by SHA-256) by
\`scripts/ffmpeg/build.sh\`, which lists every configure option. It contains no GPL or
non-free parts. \`ffmpeg.exe\` and \`ffprobe.exe\` are installed in the app's \`tools\` folder
with their license texts (\`FFMPEG-LICENSE.txt\`, \`LAME-LICENSE.txt\`) and build details
(\`FFMPEG-BUILD-INFO.txt\`); you may replace them with your own build.

## Downloaded on first use (not in the installer)

| Component | Version | License | Use |
|---|---|---|---|
| yt-dlp | 2026.08.19, then updated automatically | Unlicense | Finding and downloading videos; run as a separate program |

## Provided by Windows

Microsoft Edge WebView2 Runtime (renders the app's windows).

## Rust crates (${rust.length})

${table(rust)}

## User interface packages (${npm.length})

${table(npm)}
`,
);
console.log(`THIRD_PARTY_NOTICES.md: ${rust.length} crates, ${npm.length} npm packages`);
